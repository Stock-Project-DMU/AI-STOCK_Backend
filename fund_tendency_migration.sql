USE aistock;

-- 실행 전 확인용 — 영향받는 행 수를 미리 확인하고 싶으면 마이그레이션 전에 따로 실행해볼 것:
-- SELECT fund_tendency, COUNT(*) FROM investment_profile GROUP BY fund_tendency;

UPDATE investment_profile
SET fund_tendency = CASE fund_tendency
    WHEN 1 THEN 3   -- 목돈 모으기·저축 → 목표달성형
    WHEN 2 THEN 1   -- 자산 늘리기 → 수익추구형
    WHEN 3 THEN 3   -- 채무 상환 → 목표달성형 (그대로)
    WHEN 4 THEN 2   -- 생활비 마련 → 자유소비형
    ELSE fund_tendency
END
WHERE fund_tendency IN (1, 2, 3, 4);

